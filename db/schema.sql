-- Working state of the order pipeline. Idempotent: safe to apply on every deploy.
-- Lives next to n8n's own tables, isolated in a separate schema.
SET client_min_messages TO warning; -- hide "already exists, skipping" notices on re-apply
CREATE SCHEMA IF NOT EXISTS leadgen;
SET search_path TO leadgen;

CREATE TABLE IF NOT EXISTS sites (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token           uuid NOT NULL UNIQUE,          -- sent by the landing page, identifies the site
    name            text NOT NULL,
    email_from      text NOT NULL,
    email_from_name text NOT NULL,
    email_reply_to  text,
    email_verified_url text NOT NULL,           -- landing page shown after the verification link is clicked
    duplicate_days  integer NOT NULL DEFAULT 30    -- a previous deal younger than this makes a duplicate
);

CREATE TABLE IF NOT EXISTS products (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id                 integer NOT NULL REFERENCES sites (id),
    external_id             text NOT NULL,         -- product id as sent by the landing page
    name                    text NOT NULL,
    price                   numeric(10, 2) NOT NULL,
    hubspot_pipeline        text,
    hubspot_stage           text,
    hubspot_duplicate_stage text,
    required_fields         jsonb NOT NULL DEFAULT '[]', -- required on top of the common set
    UNIQUE (site_id, external_id)
);

-- Company-level provider accounts. Secrets stay in n8n credentials, never here.
CREATE TABLE IF NOT EXISTS providers (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type   text NOT NULL,                          -- hubspot, meta, email
    name   text NOT NULL UNIQUE,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS site_providers (
    site_id     integer NOT NULL REFERENCES sites (id),
    provider_id integer NOT NULL REFERENCES providers (id),
    active      boolean NOT NULL DEFAULT true,
    settings    jsonb NOT NULL DEFAULT '{}',       -- per-site settings, e.g. {"pixel_id": "..."}
    PRIMARY KEY (site_id, provider_id)
);

-- Verification is a property of the address: later orders skip the verification email.
CREATE TABLE IF NOT EXISTS verified_emails (
    email       text PRIMARY KEY,                  -- lowercased
    verified_at timestamptz NOT NULL DEFAULT now()
);

-- Traffic source reference. The workflow resolves a source by code, so the rows ship with the schema.
CREATE TABLE IF NOT EXISTS sources (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL
);

INSERT INTO sources (code, name)
