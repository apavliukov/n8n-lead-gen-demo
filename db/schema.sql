-- Order state is a set of facts rather than a status column:
--   blocked            -> denied at intake, never processed
--   duplicate = 2      -> recent deal found in the CRM, never processed
--   completed_at       -> every applicable step succeeded
--   next_attempt_at    -> when the scheduler picks the order up; NULL when nothing is scheduled
-- An order with no completed_at and no next_attempt_at has run out of attempts.
CREATE TABLE IF NOT EXISTS orders (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000) PRIMARY KEY, -- also the order number
    site_id         integer NOT NULL REFERENCES sites (id),
    product_id      integer NOT NULL REFERENCES products (id),
    source_id       integer NOT NULL REFERENCES sources (id),
    idempotency_key text NOT NULL,                 -- generated by the landing page per form load
    verification_token uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE, -- secret part of the email verification link
    email           text NOT NULL,                 -- lowercased
    phone           text,                          -- normalized to +49...
    payload         jsonb NOT NULL,                -- form data as received
    meta            jsonb NOT NULL DEFAULT '{}',   -- ip, user agent, utm
    blocked         boolean NOT NULL DEFAULT false,
    duplicate       smallint NOT NULL DEFAULT 0,   -- 0 no, 1 good (deal goes to the duplicates stage), 2 bad (never processed)
    attempts        integer NOT NULL DEFAULT 0,    -- failed processing runs, drives the retry backoff
    next_attempt_at timestamptz,                   -- unverified email: created_at + 2 hours
    locked_at       timestamptz,                   -- claim marker, prevents concurrent processing
    completed_at    timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (site_id, idempotency_key)
);

CREATE INDEX IF NOT EXISTS orders_email_idx ON orders (email);
CREATE INDEX IF NOT EXISTS orders_due_idx ON orders (next_attempt_at) WHERE next_attempt_at IS NOT NULL;

-- One row per successful provider action; its presence makes the step a no-op on retry.
CREATE TABLE IF NOT EXISTS provider_records (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint NOT NULL REFERENCES orders (id),
    provider_id integer NOT NULL REFERENCES providers (id),
    type        text NOT NULL,                     -- email_verification, hubspot_contact, hubspot_deal, email_order_received, meta_purchase
    external_id text,
    response    jsonb,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (order_id, type)
);
